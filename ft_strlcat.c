#include "libft.h"

size_t	ft_strlcat(char *dest, const char *src, size_t size)
{
	size_t	i;
	size_t	len_dest;
	size_t	len_src;

	len_dest = 0;
	while (len_dest < size && dest[len_dest])
		len_dest++;
	len_src = ft_strlen(src);
	if (size <= len_dest)
		return (len_src + size);
	i = 0;
	while (src[i] != '\0' && i < size - len_dest - 1)
	{
		dest[len_dest + i] = src[i];
		i++;
	}
	dest[len_dest + i] = '\0';
	return (len_dest + len_src);
}
